"""gen_handpose_data.py - turn the left-hand finger poses saved in the Arcade Controls era
re2_vr_reload.json (RE2VRMODRELOADED's left_hand_pose block, credit: Andyalpa) into src/handpose_data.h.
Usage: python tools/gen_handpose_data.py <re2_vr_reload.json> > src/handpose_data.h"""
import json, sys
BONES = ["l_hand_index_0", "l_hand_index_1", "l_hand_index_2",
         "l_hand_middle_0", "l_hand_middle_1", "l_hand_middle_2",
         "l_hand_ring_0", "l_hand_ring_1", "l_hand_ring_2", "l_hand_ring_3",
         "l_hand_little_0", "l_hand_little_1", "l_hand_little_2", "l_hand_little_3",
         "l_hand_thumb_0", "l_hand_thumb_1", "l_hand_thumb_2"]
CTX = {"mag_hold": "MAG", "slide_rack": "SLIDE"}
d = json.load(open(sys.argv[1], encoding="utf-8"))["left_hand_pose"]
rows = []
for ctx, tag in CTX.items():
    for wp, ent in sorted((d.get(ctx) or {}).get("by_wp", {}).items()):
        for prof in ("leon", "claire"):
            pose = (ent.get(prof) or {}).get("pose") or {}
            if not all(b in pose for b in BONES):
                continue
            vals = ", ".join("{%.6ff, %.6ff, %.6ff}" % tuple(pose[b][:3]) for b in BONES)
            rows.append("    {Ctx::%s, %d, %s, {%s}}," % (tag, int(wp[2:]), "true" if prof == "claire" else "false", vals))
print("// handpose_data.h -- GENERATED by tools/gen_handpose_data.py, do not edit by hand.")
print("// Left-hand finger poses (local Euler angles, radians, the order of kBones) from the RE2VRMODRELOADED")
print("// left_hand_pose data as saved in the Arcade Controls era config (credit: Andyalpa).")
print("#pragma once\n\nnamespace vn::handpose {\n")
print("enum class Ctx { MAG, SLIDE };")
print("constexpr int kBoneCount = %d;" % len(BONES))
print("constexpr const wchar_t* kBones[kBoneCount] = {\n    " + ",\n    ".join('L"%s"' % b for b in BONES) + "};\n")
print("struct FingerPose { Ctx ctx; int wp; bool claire; float a[kBoneCount][3]; };")
print("constexpr FingerPose kPoses[] = {")
print("\n".join(rows))
print("};\n\n} // namespace vn::handpose")
print("%d poses" % len(rows), file=sys.stderr)
