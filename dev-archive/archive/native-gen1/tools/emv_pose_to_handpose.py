"""emv_pose_to_handpose.py - put left-hand finger poses made in alphaZomega's EMV Engine Poser into src/handpose_data.h.

Tefa 2026-10-10: "I think we have to use the EMV engine to redo all the hand poses". EMV's Poser works flat (not in VR,
2026-10-11); its "Save Pose" writes reframework/data/EMV_Engine/Poses/<object>.json as
    { "<slot name>": { "<joint>": { "_LocalEulerAngle": "vec:x y z", ... }, ... }, ... }
which is the same joint property handpose.cpp writes (LocalEulerAngle, radians). So a pose made there needs no
conversion beyond picking the 17 left-hand finger joints.

Name each EMV pose slot "<mag|slide> wp<number> <leon|claire>": "mag wp0000 leon" is the magazine / shell hold for
gun wp0000 (the Matilda) as Leon, "slide wp0000 leon" the hand on its slide / pump. The numbers are the game's own
weapon numbers, as in handpose_data.h.
Slots with other names are ignored and listed.

Usage:
    python tools/emv_pose_to_handpose.py <EMV Poses json> [--data src/handpose_data.h] [--write]
Without --write it only prints what would change. A pose in the EMV file replaces the built-in one with the same
(kind, gun, character); a new one is added. Then rebuild (tools/build.sh)."""
import argparse
import re
import sys

BONES = ["l_hand_index_0", "l_hand_index_1", "l_hand_index_2",
         "l_hand_middle_0", "l_hand_middle_1", "l_hand_middle_2",
         "l_hand_ring_0", "l_hand_ring_1", "l_hand_ring_2", "l_hand_ring_3",
         "l_hand_little_0", "l_hand_little_1", "l_hand_little_2", "l_hand_little_3",
         "l_hand_thumb_0", "l_hand_thumb_1", "l_hand_thumb_2"]
SLOT = re.compile(r"^\s*(mag|slide)\s+wp(\d+)\s+(leon|claire)\s*$", re.I)
ROW = re.compile(r"^\s*\{Ctx::(MAG|SLIDE), (\d+), (true|false), \{(.*)\}\},\s*$")
TRIPLE = re.compile(r"\{(-?[\d.]+)f, (-?[\d.]+)f, (-?[\d.]+)f\}")


def parse_vec(v):
    """EMV writes a vector as "vec:x y z"; older files or hand edits may hold a list."""
    if isinstance(v, str) and v.startswith("vec:"):
        parts = v[4:].split()
    elif isinstance(v, (list, tuple)):
        parts = v
    else:
        raise ValueError("not a vector: %r" % (v,))
    if len(parts) < 3:
        raise ValueError("a vector needs three numbers: %r" % (v,))
    return tuple(float(p) for p in parts[:3])


def poses_from_emv(emv):
    """{(ctx, wp, claire): [17 triples]} and the list of slots that were skipped, with why."""
    out, skipped = {}, []
    for slot, joints in emv.items():
        m = SLOT.match(slot)
        if not m:
            skipped.append((slot, "name is not '<mag|slide> wp<number> <leon|claire>'"))
            continue
        missing = [b for b in BONES if b not in joints or "_LocalEulerAngle" not in joints[b]]
        if missing:
            skipped.append((slot, "no finger angles for " + ", ".join(missing[:3]) + ("..." if len(missing) > 3 else "")))
            continue
        key = (m.group(1).upper(), int(m.group(2)), m.group(3).lower() == "claire")
        out[key] = [parse_vec(joints[b]["_LocalEulerAngle"]) for b in BONES]
    return out, skipped


def read_rows(text):
    """the kPoses rows of handpose_data.h, in order: [(key, triples)]"""
    rows = []
    for line in text.splitlines():
        m = ROW.match(line)
        if m:
            vals = [tuple(float(x) for x in t) for t in TRIPLE.findall(m.group(4))]
            if len(vals) != len(BONES):
                raise ValueError("a row with %d joints, not %d: %s" % (len(vals), len(BONES), line[:60]))
            rows.append(((m.group(1), int(m.group(2)), m.group(3) == "true"), vals))
    return rows


def row_text(key, vals):
    ctx, wp, claire = key
    body = ", ".join("{%.6ff, %.6ff, %.6ff}" % t for t in vals)
    return "    {Ctx::%s, %d, %s, {%s}}," % (ctx, wp, "true" if claire else "false", body)


def merge(text, new):
    """handpose_data.h with the new poses in place of the old ones (same key) or appended; and what changed."""
    rows = read_rows(text)
    keys = [k for k, _ in rows]
    changed = []
    merged = []
    for k, vals in rows:
        if k in new:
            changed.append(("replaced", k))
            merged.append((k, new[k]))
        else:
            merged.append((k, vals))
    for k in sorted(new):
        if k not in keys:
            changed.append(("added", k))
            merged.append((k, new[k]))
    lines = text.splitlines()
    first = next(i for i, l in enumerate(lines) if ROW.match(l))
    last = max(i for i, l in enumerate(lines) if ROW.match(l))
    out = lines[:first] + [row_text(k, v) for k, v in merged] + lines[last + 1:]
    head = "// handpose_data.h -- GENERATED by tools/gen_handpose_data.py, do not edit by hand."
    note = "// Poses from EMV Engine's Poser were merged in by tools/emv_pose_to_handpose.py (see that file)."
    if out and out[0] == head and note not in out:
        out.insert(1, note)
    return "\n".join(out) + "\n", changed


def describe(key):
    ctx, wp, claire = key
    return "%s wp%04d %s" % ("magazine/shell hold" if ctx == "MAG" else "hand on the slide/pump", wp, "claire" if claire else "leon")


def main():
    import json
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("emv")
    ap.add_argument("--data", default="src/handpose_data.h")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    new, skipped = poses_from_emv(json.load(open(a.emv, encoding="utf-8")))
    for slot, why in skipped:
        print("skipped %r: %s" % (slot, why))
    if not new:
        print("no usable poses in %s" % a.emv)
        return 1
    text = open(a.data, encoding="utf-8").read()
    out, changed = merge(text, new)
    for what, k in changed:
        print("%s: %s" % (what, describe(k)))
    if a.write:
        open(a.data, "w", encoding="utf-8", newline="\n").write(out)
        print("written %s; now rebuild" % a.data)
    else:
        print("(dry run; --write to change %s)" % a.data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
